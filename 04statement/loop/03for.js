/*
For Loop

A for loop is a looping statement in JavaScript used to execute a block of 
code repeatedly for a fixed number of times.
It is commonly used when the number of iterations is already known.

In simple words
"For loop repeats code until the condition becomes false."

Syntax

for(initialization; condition; increment/decrement) {
   // code to execute
}

*/
for(let i = 1; i <= 5; i++) {
   console.log(i);
}

