/*
If Statement 
An if statement is a decision-making statement in JavaScript that checks a 
condition and executes a block of code only when the condition is true.
It helps the program make decisions based on different situations. If the 
condition is false, the code inside the if block will not run.

In simple words
"If a condition is true, then execute the code." 

Syntax
if (condition) {
   // code to be executed
}
*/

