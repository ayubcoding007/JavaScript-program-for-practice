let a = 10;

console.log("Initial value:", a);

a += 5;   // a = a + 5
console.log("After += :", a);

a -= 3;   // a = a - 3
console.log("After -= :", a);

a *= 2;   // a = a * 2
console.log("After *= :", a);

a /= 4;   // a = a / 4
console.log("After /= :", a);

a %= 3;   // a = a % 3
console.log("After %= :", a);

a **= 2;  // a = a ** 2
console.log("After **= :", a);